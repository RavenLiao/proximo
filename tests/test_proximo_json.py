import json
import tomllib

import pytest

from proximo.core import apitree, diagnose, engine, search
from proximo.core.errors import ProximoError
from test_tiers_harvest import bj  # the build, with its checks


def test_the_shipped_file_is_what_the_records_build():
    # the JSON inside, not the gzip wrapper: zlib builds differ between interpreters (3.12 vs 3.13 red)
    assert bj.inside(bj.OUT.read_bytes()) == bj.inside(bj.assemble()), \
        "proximo.json.gz is not what records/ builds: run scripts/build_proximo_json.py"


def test_the_built_header_names_every_input_by_hash():
    doc = json.loads(gzip.decompress(bj.OUT.read_bytes()))
    assert set(doc["built"]["inputs"]) == {"vendor.json.gz", *bj.AUTHORED}


def test_a_record_edited_without_a_rebuild_is_seen(tmp_path):
    """THE CONTROL: one tier changed in a copy of records/, and the copy no longer builds the
    shipped file."""
    for f in bj.RECORDS.iterdir():
        (tmp_path / f.name).write_bytes(f.read_bytes())
    tiers = tmp_path / "tiers.toml"
    text = tiers.read_text()
    assert 'tier = "destructive"' in text
    tiers.write_text(text.replace('tier = "destructive"', 'tier = "disruptive"', 1))
    assert bj.inside(bj.assemble(tmp_path)) != bj.inside(bj.OUT.read_bytes())


def _serve(monkeypatch, doc):
    """Stand `doc` where the package's file is, gzipped, and clear every cache built from it."""
    from conftest import _clear_data_caches

    blob = gzip.compress(json.dumps(doc).encode())

    class _File:
        def joinpath(self, _name):
            return self

        def read_bytes(self):
            return blob

    real = apitree.resources.files
    monkeypatch.setattr(apitree.resources, "files", lambda pkg: _File() if pkg == "proximo.core" else real(pkg))
    _clear_data_caches()


def _shipped():
    return json.loads(gzip.decompress(bj.OUT.read_bytes()))


def _no_rules(doc):               # the door would serve the credentials the record withholds
    for r in doc["rows"]:
        r["secret"], r["arg_secrets"] = None, []


def _no_untrusted(doc):           # every guest-written answer would read as clean
    for r in doc["rows"]:
        r["untrusted"], r["channel"] = False, None


#: One damage per shape the loader refuses: on the first row, or on the document.
_ROW_DAMAGE = {
    "missing column": lambda r: r.pop("untrusted"),
    "extra column": lambda r: r.update(note="a column the engine does not govern"),
    "wrong type": lambda r: r.update(untrusted="no"),
    "bad secret": lambda r: r.update(secret={"drop": []}),
    "unknown plane": lambda r: r.update(product="pxx"),
    "unknown lane": lambda r: r.update(lane="metal"),          # opt_in_refusal names four lanes
    "net half named": lambda r: r.update(net={"snapshot": "POST /nodes/{node}/lxc/{vmid}/snapshot"}),
    "expect not a state": lambda r: r.update(expect={"status": 1}),
    "twin names no row": lambda r: r.update(twin="/nowhere/{node}"),        # a KeyError at plan time is not a refusal
    "task status names no row": lambda r: r.update(task_status="/nowhere/{upid}/status"),
    "net names no row": lambda r: r.update(net={"snapshot": "POST /nowhere/{vmid}/snapshot",
                                               "rollback": "POST /nowhere/{snapname}/rollback"}),
    # a net address with no method was an IndexError in the refusal's own words
    "net address without a space": lambda r: r.update(net={"snapshot": "nospace", "rollback": ""}),
}
_DOC_DAMAGE = {
    "address twice": lambda d: d["rows"].append(dict(d["rows"][0])),
    "wrong schema": lambda d: d.update(schema=2),
    "no rows": lambda d: d.update(rows=[]),
    "no secret rule": _no_rules,
    "no untrusted row": _no_untrusted,
    "no diagnose battery": lambda d: d.pop("diagnose"),
    "empty battery": lambda d: d.update(diagnose=[]),
    "battery as a table": lambda d: d.update(diagnose={s["key"]: s for s in d["diagnose"]}),   # loses the order
    "no find vocabulary": lambda d: d.update(vocab="guest"),
}


def _damaged(how):
    doc = _shipped()
    if how in _ROW_DAMAGE:
        _ROW_DAMAGE[how](doc["rows"][0])
    else:
        _DOC_DAMAGE[how](doc)
    return doc


@pytest.mark.parametrize("how", [*_ROW_DAMAGE, *_DOC_DAMAGE])
def test_a_damaged_file_refuses_every_address(monkeypatch, how):
    from conftest import _clear_data_caches

    _serve(monkeypatch, _damaged(how))
    try:
        with pytest.raises(ProximoError, match="proximo.json.gz"):
            engine.resolve("pve", "GET", "/version")
    finally:
        monkeypatch.undo()
        _clear_data_caches()


_EXEC = ("pve", "POST", "/nodes/{node}/lxc/{vmid}/exec")
_START = ("pve", "POST", "/nodes/{node}/qemu/{vmid}/status/start")
_GETCFG = ("pve", "GET", "/nodes/{node}/qemu/{vmid}/config")
_PUTCFG = ("pve", "PUT", "/nodes/{node}/qemu/{vmid}/config")
_CUR = "/nodes/{node}/qemu/{vmid}/status/current"
_TASK = "/nodes/{node}/tasks/{upid}/status"
_NET = {"snapshot": "POST /nodes/{node}/lxc/{vmid}/snapshot",
        "rollback": "POST /nodes/{node}/lxc/{vmid}/snapshot/{snapname}/rollback"}
_QNET = {"snapshot": "POST /nodes/{node}/qemu/{vmid}/snapshot",
         "rollback": "POST /nodes/{node}/qemu/{vmid}/snapshot/{snapname}/rollback"}
_BOOL = {"type": "boolean", "optional": True, "description": "snapshot first"}


def _at(rows, key):
    return next(r for r in rows if (r["product"], r["method"], r["path"]) == key)


#: Lens 3 F8: every column named a row the file carried and the loader served it, on any row.
#: One damage per rule the build keeps and the engine reads without a guard; each on a named row,
#: and (lens 4 L4-2) one per CLAUSE of a rule, shaped so no sibling clause refuses it first.
_COLUMN_DAMAGE = {
    "lane on an ungated row": (_GETCFG, lambda r, rows: r.update(lane="agent")),
    "twin on a read": (_GETCFG, lambda r, rows: r.update(twin=_GETCFG[2])),
    "state on a read": (_GETCFG, lambda r, rows: r.update(state=_CUR)),
    "expect on a read": (_GETCFG, lambda r, rows: r.update(expect={"status": "running"})),
    "task status on a read": (_GETCFG, lambda r, rows: r.update(task_status=_TASK)),
    "twin not the row's own path": (_PUTCFG, lambda r, rows: r.update(twin="/nodes/{node}/qemu")),
    "state not the parent's current": (_START, lambda r, rows: r.update(state=_GETCFG[2])),
    "state beside a served twin": (_PUTCFG, lambda r, rows: r.update(state=_CUR)),
    "expect without a state": (_PUTCFG, lambda r, rows: r.update(expect={"status": "running"})),
    "expect not a status": (_START, lambda r, rows: r.update(expect={"stopped": "yes"})),
    "a mutation with no task status": (_START, lambda r, rows: r.update(task_status=None)),  # it would not poll
    "task status not a task read": (_START, lambda r, rows: r.update(task_status="/nodes/{node}/qemu")),
    "net on an http row": (_START, lambda r, rows: r.update(net=_NET)),
    "net on another container's path": (_EXEC, lambda r, rows: r.update(net={
        "snapshot": "POST /nodes/{node}/qemu/{vmid}/snapshot",
        "rollback": "POST /nodes/{node}/qemu/{vmid}/snapshot/{snapname}/rollback"})),
    "net rollback a delete": (_EXEC, lambda r, rows: r.update(
        net={**_NET, "rollback": "DELETE /nodes/{node}/lxc/{vmid}"})),
    "net snapshot naming its own snapname": (_EXEC, lambda r, rows: r.update(
        net={**_NET, "snapshot": _NET["rollback"]})),
    # lens 4 L4-2: the clause alone, with every sibling clause satisfied
    "state on the current read itself": (("pve", "GET", _CUR), lambda r, rows: r.update(state=_CUR)),
    "state beside a served twin at the parent's current": (_START, lambda r, rows: (
        rows.append({**_at(rows, _GETCFG), "path": _START[2]}), r.update(twin=_START[2]))),
    "net on an http row with the snapshot param": (_PUTCFG, lambda r, rows: (
        r["params"].update(snapshot=_BOOL), r.update(net=_QNET))),
    "net beside a snapshot param that is not a boolean": (_EXEC, lambda r, rows: r["params"].update(
        snapshot={**_BOOL, "type": "string"})),
    "net rollback naming no snapshot": (_EXEC, lambda r, rows: r.update(
        net={**_NET, "rollback": "POST /nodes/{node}/lxc/{vmid}/status/stop"})),
}


@pytest.mark.parametrize("how", list(_COLUMN_DAMAGE))
def test_a_column_the_build_would_not_write_refuses_every_address(monkeypatch, how):
    from conftest import _clear_data_caches

    doc = _shipped()
    key, damage = _COLUMN_DAMAGE[how]
    damage(_at(doc["rows"], key), doc["rows"])
    _serve(monkeypatch, doc)
    try:
        with pytest.raises(ProximoError, match="proximo.json.gz"):
            engine.resolve("pve", "GET", "/version")
    finally:
        monkeypatch.undo()
        _clear_data_caches()


#: Lens 4 L4-3: the named-row check's own cases. Each column keeps the shape the build writes
#: (the state IS the parent's /current, the twin IS the row's own path, the task IS a task read,
