def test_the_net_is_authored_and_the_build_holds_it_to_the_table(records):
    """The exec and psql rows carry the snapshot and its rollback; a net naming an address the door
    does not serve, or a snapshot parameter without a net, refuses the build by name."""
    net = engine.table()[("pve", "POST", "/nodes/{node}/lxc/{vmid}/exec")].net
    assert dict(net) == {"snapshot": "POST /nodes/{node}/lxc/{vmid}/snapshot",
                         "rollback": "POST /nodes/{node}/lxc/{vmid}/snapshot/{snapname}/rollback"}
    assert sum(1 for r in engine.table().values() if r.net) == 2
    real = bj.read_inputs()[1]["shell.toml"]
    line = ('net = { snapshot = "POST /nodes/{node}/lxc/{vmid}/snapshot", '
            'rollback = "POST /nodes/{node}/lxc/{vmid}/snapshot/{snapname}/rollback" }')
    assert real.count(line) == 2
    with pytest.raises(ProximoError, match="net snapshot 'POST /nodes/{node}/lxc/{vmid}/snapshotx' is not a mutation"):
        records(**{"shell.toml": real.replace("/snapshot\"", "/snapshotx\"", 1)})
    with pytest.raises(ProximoError, match="net rollback .* is not a mutation"):
        records(**{"shell.toml": real.replace("{snapname}/rollback", "{snapname}/rollbackx", 1)})
    with pytest.raises(ProximoError, match="come together"):
        records(**{"shell.toml": real.replace(line + "\n", "", 1)})
    with pytest.raises(ProximoError, match="net rollback .* is not a mutation"):   # a DELETE is not the rollback
        records(**{"shell.toml": real.replace('rollback = "POST /nodes', 'rollback = "DELETE /nodes', 1)})
    with pytest.raises(ProximoError, match="net snapshot .* is not a mutation"):   # the rollback route as snapshot
        snap = 'snapshot = "POST /nodes/{node}/lxc/{vmid}/snapshot'
        records(**{"shell.toml": real.replace(snap + '"', snap + '/{snapname}/rollback"', 1)})


def test_the_secret_column_is_the_own_line_merged_with_the_read_twins():
    """A mutation with no own line carries its GET twin's rule; one with both carries the union,
    bearer from the own line; a read carries its own line alone."""
    t = _index()
    reads, _ = bj.secrets(bj.read_inputs()[1]["secrets.toml"])
    merged = 0
    for (p, m, path), r in t.items():
        own, twin = reads.get(f"{p}:{m} {path}"), reads.get(f"{p}:GET {path}") if m != "GET" else None
        assert r["secret"] == bj.merged_secret(own, twin), (p, m, path)
        merged += own is None and twin is not None
    assert merged == 88 and len(reads) == 90          # 97 lines: 90 read rules, 7 arg-only


def test_an_authored_name_or_key_never_renames_a_subject_or_a_probe(records):
    """Lens 2 on D3 (L2-2): a `name = "zzz"` under a probe table won the merge and the probe was
    served as zzz. The table key is the name; the build refuses the field."""
    real = bj.read_inputs()[1]["diagnose.toml"]
    with pytest.raises(ProximoError, match="nothing renames it"):
        records(**{"diagnose.toml": real.replace('[subject."pve:GET /nodes/{node}".probe.status]',
                                                 '[subject."pve:GET /nodes/{node}".probe.status]\nname = "zzz"', 1)})
    with pytest.raises(ProximoError, match="nothing renames it"):
        records(**{"diagnose.toml": real.replace('[subject."pve:GET /nodes/{node}"]',
                                                 '[subject."pve:GET /nodes/{node}"]\nkey = "zzz"', 1)})
