"""The one JSON: what ships is what `records/` builds, and a damaged one refuses every address.

`src/proximo/core/proximo.json.gz` is generated by `scripts/build_proximo_json.py` from the vendor
stage and the authored records. A record edited without a rebuild is red here; a file that is not
exactly the shape the engine governs refuses the load whole, never read with a default.
"""
import gzip
import json
import tomllib

import pytest

from proximo.core import apitree, diagnose, engine, search
from proximo.core.errors import ProximoError
from test_tiers_harvest import bj  # the build, with its checks


def test_the_shipped_file_is_what_the_records_build():
    # the JSON inside, not the gzip wrapper: zlib builds differ between interpreters (3.12 vs 3.13 red)
    assert bj.inside(bj.OUT.read_bytes()) == bj.inside(bj.assemble()), \
        "proximo.json.gz is not what records/ builds: run scripts/build_proximo_json.py"


def test_the_built_header_names_every_input_by_hash():
    doc = json.loads(gzip.decompress(bj.OUT.read_bytes()))
    assert set(doc["built"]["inputs"]) == {"vendor.json.gz", *bj.AUTHORED}


def test_a_record_edited_without_a_rebuild_is_seen(tmp_path):
    """THE CONTROL: one tier changed in a copy of records/, and the copy no longer builds the
    shipped file."""
    for f in bj.RECORDS.iterdir():
        (tmp_path / f.name).write_bytes(f.read_bytes())
    tiers = tmp_path / "tiers.toml"
    text = tiers.read_text()
    assert 'tier = "destructive"' in text
    tiers.write_text(text.replace('tier = "destructive"', 'tier = "disruptive"', 1))
    assert bj.inside(bj.assemble(tmp_path)) != bj.inside(bj.OUT.read_bytes())


def _serve(monkeypatch, doc):
    """Stand `doc` where the package's file is, gzipped, and clear every cache built from it."""
    from conftest import _clear_data_caches

    blob = gzip.compress(json.dumps(doc).encode())

    class _File:
        def joinpath(self, _name):
            return self

        def read_bytes(self):
            return blob

    real = apitree.resources.files
    monkeypatch.setattr(apitree.resources, "files", lambda pkg: _File() if pkg == "proximo.core" else real(pkg))
    _clear_data_caches()


def _shipped():
    return json.loads(gzip.decompress(bj.OUT.read_bytes()))


def _no_rules(doc):               # the door would serve the credentials the record withholds
    for r in doc["rows"]:
        r["secret"], r["arg_secrets"] = None, []


def _no_untrusted(doc):           # every guest-written answer would read as clean
    for r in doc["rows"]:
        r["untrusted"], r["channel"] = False, None


#: One damage per shape the loader refuses: on the first row, or on the document.
_ROW_DAMAGE = {
    "missing column": lambda r: r.pop("untrusted"),
    "extra column": lambda r: r.update(note="a column the engine does not govern"),
    "wrong type": lambda r: r.update(untrusted="no"),
    "bad secret": lambda r: r.update(secret={"drop": []}),
    "unknown plane": lambda r: r.update(product="pxx"),
    "unknown lane": lambda r: r.update(lane="metal"),          # opt_in_refusal names four lanes
    "net half named": lambda r: r.update(net={"snapshot": "POST /nodes/{node}/lxc/{vmid}/snapshot"}),
    "expect not a state": lambda r: r.update(expect={"status": 1}),
    "twin names no row": lambda r: r.update(twin="/nowhere/{node}"),        # a KeyError at plan time is not a refusal
    "task status names no row": lambda r: r.update(task_status="/nowhere/{upid}/status"),
    "net names no row": lambda r: r.update(net={"snapshot": "POST /nowhere/{vmid}/snapshot",
                                               "rollback": "POST /nowhere/{snapname}/rollback"}),
    # a net address with no method was an IndexError in the refusal's own words
    "net address without a space": lambda r: r.update(net={"snapshot": "nospace", "rollback": ""}),
}
_DOC_DAMAGE = {
    "address twice": lambda d: d["rows"].append(dict(d["rows"][0])),
    "wrong schema": lambda d: d.update(schema=2),
    "no rows": lambda d: d.update(rows=[]),
    "no secret rule": _no_rules,
    "no untrusted row": _no_untrusted,
    "no diagnose battery": lambda d: d.pop("diagnose"),
    "empty battery": lambda d: d.update(diagnose=[]),
    "battery as a table": lambda d: d.update(diagnose={s["key"]: s for s in d["diagnose"]}),   # loses the order
    "no find vocabulary": lambda d: d.update(vocab="guest"),
}


def _damaged(how):
    doc = _shipped()
    if how in _ROW_DAMAGE:
        _ROW_DAMAGE[how](doc["rows"][0])
    else:
        _DOC_DAMAGE[how](doc)
    return doc


@pytest.mark.parametrize("how", [*_ROW_DAMAGE, *_DOC_DAMAGE])
def test_a_damaged_file_refuses_every_address(monkeypatch, how):
    from conftest import _clear_data_caches

    _serve(monkeypatch, _damaged(how))
    try:
        with pytest.raises(ProximoError, match="proximo.json.gz"):
            engine.resolve("pve", "GET", "/version")
    finally:
        monkeypatch.undo()
        _clear_data_caches()


def test_the_battery_and_the_vocabulary_keep_their_authored_order():
    """The build serialises with sorted keys; the two sections are lists so the record's own order
    (status, storage, tasks ... not alphabetical) is what DIAGNOSE runs and contract 1 samples."""
    bat = tomllib.loads((bj.RECORDS / "diagnose.toml").read_text())["subject"]
    assert list(diagnose.subjects()) == list(bat)
    for key, spec in bat.items():
        assert list(diagnose.subjects()[key].probes) == list(spec["probe"])
    assert list(search.synonyms()) == list(tomllib.loads((bj.RECORDS / "vocab.toml").read_text())["synonym"])
    assert list(bat["pve:GET /nodes/{node}"]["probe"])[:3] == ["status", "storage", "tasks"]  # not sorted


def test_an_unreadable_file_refuses_every_address(monkeypatch):
    from conftest import _clear_data_caches

    class _File:
        def joinpath(self, _name):
            return self

        def read_bytes(self):
            return b"not a gzip"

    real = apitree.resources.files
    monkeypatch.setattr(apitree.resources, "files", lambda pkg: _File() if pkg == "proximo.core" else real(pkg))
    _clear_data_caches()
    try:
        with pytest.raises(ProximoError, match="cannot be read"):
            engine.resolve("pve", "GET", "/version")
    finally:
        monkeypatch.undo()
        _clear_data_caches()


def test_a_corrupted_gzip_refuses_every_address_with_the_refusal_not_a_traceback(monkeypatch):
    """Bytes flipped INSIDE the deflate stream (not the header: that is `not a gzip` above) raise
    `zlib.error`, which is not an OSError; the lens found it escaping as a traceback."""
    from conftest import _clear_data_caches

    raw = bytearray(bj.OUT.read_bytes())
    for i in range(20, 40):
        raw[i] ^= 0xFF
    blob = bytes(raw)

    class _File:
        def joinpath(self, _name):
            return self

        def read_bytes(self):
            return blob

    real = apitree.resources.files
    monkeypatch.setattr(apitree.resources, "files", lambda pkg: _File() if pkg == "proximo.core" else real(pkg))
    _clear_data_caches()
    try:
        with pytest.raises(ProximoError, match="cannot be read"):
            engine.resolve("pve", "GET", "/version")
    finally:
        monkeypatch.undo()
        _clear_data_caches()


def test_the_control_the_shipped_file_served_the_same_way_loads(monkeypatch):
    """The stand-in itself is not what refuses: the shipped document, served through it, loads."""
    from conftest import _clear_data_caches

    _serve(monkeypatch, _shipped())
    try:
        assert engine.resolve("pve", "GET", "/version").access == "read"
    finally:
        monkeypatch.undo()
        _clear_data_caches()


# ---- the columns the build computes: each is the table's own geometry, held row by row ----------

def _index():
    return {(r["product"], r["method"], r["path"]): r for r in _shipped()["rows"]}


def test_the_read_columns_are_the_tables_own_geometry():
    """`twin` iff a GET is published at the same path; `state` iff no served twin and the parent's
    `/current` is served; `expect` only on the four actions with a status to aim at."""
    t = _index()
    seen = {"twin": 0, "state": 0, "expect": 0}
    for (p, m, path), r in t.items():
        if r["access"] != "mutate":
            assert r["twin"] is None and r["state"] is None and r["expect"] is None, (p, m, path)
            continue
        same = t.get((p, "GET", path))
        assert r["twin"] == (path if same is not None else None), (p, m, path)
        parent, _, action = path.rpartition("/")
        cur = t.get((p, "GET", parent + "/current"))
        served = cur is not None and not cur["excluded"] and not cur["gate"]
        want = parent + "/current" if (same is None or same["excluded"]) and served else None
        assert r["state"] == want, (p, m, path)
        expect = {"status": bj.EXPECTED[action]} if want and action in bj.EXPECTED else None
        assert r["expect"] == expect, (p, m, path)
        for k in seen:
            seen[k] += r[k] is not None
    assert seen == {"twin": 552, "state": 15, "expect": 8}      # 543 served, 1 gated, 8 tunnelled; 13 power + 2 HA


def test_the_lane_column_is_the_gates_lane():
    from proximo.core import rawdoor, shell
    for r in _shipped()["rows"]:
        if not r["gate"]:
            assert r["lane"] is None, r["path"]
        elif r["wire"] == "ssh":
            assert r["lane"] == shell.lane_of(r["path"])
        elif rawdoor.is_stream(r["product"], r["path"]):
            assert r["lane"] == "download"
        else:
            agent = r["product"] == "pve" and r["path"].startswith(rawdoor.AGENT_PREFIX)
            assert r["lane"] == ("agent" if agent else None)
    assert {r["lane"] for r in _shipped()["rows"]} == {None, "agent", "shell", "node", "download"}


def test_task_status_is_a_read_the_plane_publishes_remote_form_under_a_remote():
    t = _index()
    for (p, m, path), r in t.items():
        if r["access"] != "mutate" or r["excluded"]:
            assert r["task_status"] is None
            continue
        assert (p, "GET", r["task_status"]) in t, (p, m, path)
        remote = path.startswith(("/pve/remotes/{remote}/", "/pbs/remotes/{remote}/"))
        assert ("{remote}" in r["task_status"]) == remote, (p, m, path)
    assert sum("{remote}" in (r["task_status"] or "") for r in t.values()) > 0


def test_a_vendor_without_the_task_address_refuses_the_build():
    vendor, texts, _ = bj.read_inputs()
    cut = [r for r in vendor if r["path"] != "/nodes/{node}/tasks/{upid}/status"]
